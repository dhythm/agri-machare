export const submissionTable: TableSpec<Submission> = {
  table: 'submissions',
  columns: ['id', 'kind', 'target_id', 'user_id', 'received_at', 'payload'],
  toRow: (submission) => [
    submission.id,
    submission.kind,
    nullable(submission.targetId),
    nullable(submission.userId),
    submission.receivedAt,
    JSON.stringify(submission.payload),
  ],
  fromRow: (row: Row) =>
    compact({
      id: row.id as string,
      kind: row.kind as Submission['kind'],
      targetId: (row.target_id as string | null) ?? undefined,
      userId: (row.user_id as string | null) ?? undefined,
      receivedAt: isoString(row.received_at) as string,
      payload: row.payload as Record<string, unknown>,
    }),
}
